-- The warehouse side of the AI BI engine: four roles, four schemas, and a landed CEM extract.
--
-- Run by the `aibi-db-init` service on EVERY start, as the kit's database owner, and idempotent — the kit's own
-- kit/initdb/ scripts run only when PostgreSQL creates its data directory, which a kit installed last week already did.
--
--   role            may                                           used by
--   bi_builder      create in `bi`, read `cem_landing`            the dbt-runner (production build)
--   aibi_dbt_dev    read `bi`, create in `bi_dev` and             the AI BI service: a generated model goes into bi_dev,
--                   `bi_factory` ONLY                             its own records (projects, gates, audit) into bi_factory
--   bi_reader       read `bi` and `bi_dev`, write nothing         the data gateway, and Superset's BI connection
--   bi_records_reader  read `bi_factory`, write nothing           Superset's SECOND connection, closed to SQL Lab:
--                                                                 the two dashboards over the engine's records
--
-- The AI service never holds bi_builder's password or the owner's: what it can damage is one schema of drafts
-- and the copy of its own records that Superset draws (the records themselves are in its volume, not here).
-- That copy holds the audit trail: the role every BI chart reads through cannot see it.
\set ON_ERROR_STOP on

select 'create role bi_builder login'   where not exists (select from pg_roles where rolname = 'bi_builder')   \gexec
select 'create role aibi_dbt_dev login' where not exists (select from pg_roles where rolname = 'aibi_dbt_dev') \gexec
select 'create role bi_reader login'    where not exists (select from pg_roles where rolname = 'bi_reader')    \gexec
select 'create role bi_records_reader login' where not exists (select from pg_roles where rolname = 'bi_records_reader') \gexec

alter role bi_builder   password :'builder_pw';
alter role aibi_dbt_dev password :'dev_pw';
alter role bi_reader    password :'reader_pw';
alter role bi_records_reader password :'records_pw';

-- Read-only in the role itself, not only in the code that uses it: a session that forgets to ask still cannot write.
alter role bi_reader set default_transaction_read_only = on;
alter role bi_reader set statement_timeout = '30s';
alter role bi_records_reader set default_transaction_read_only = on;
alter role bi_records_reader set statement_timeout = '30s';
alter role aibi_dbt_dev set statement_timeout = '120s';

create schema if not exists cem_landing;
create schema if not exists bi     authorization bi_builder;
create schema if not exists bi_dev authorization aibi_dbt_dev;
create schema if not exists bi_factory authorization aibi_dbt_dev;

comment on schema bi_factory  is 'the AI BI engine''s own records, copied here so that Superset can draw them — rewritten whole';
comment on schema cem_landing is 'the CEM extract as landed — synthetic in this kit, cem_to_mart.py''s output with a real cluster';
comment on schema bi          is 'governed dbt models (target prod) — built by the dbt-runner only';
comment on schema bi_dev      is 'models generated by the AI BI service on its own branch (target dev) — drafts';

grant usage on schema cem_landing to bi_builder;
grant usage on schema bi          to aibi_dbt_dev, bi_reader;
grant usage on schema bi_dev      to bi_reader;
grant usage on schema bi_factory  to bi_records_reader;

grant select on all tables in schema bi     to aibi_dbt_dev, bi_reader;
grant select on all tables in schema bi_dev to bi_reader;
grant select on all tables in schema bi_factory to bi_records_reader;
alter default privileges for role bi_builder   in schema bi     grant select on tables to aibi_dbt_dev, bi_reader;
alter default privileges for role aibi_dbt_dev in schema bi_dev grant select on tables to bi_reader;
alter default privileges for role aibi_dbt_dev in schema bi_factory grant select on tables to bi_records_reader;
-- an install that ran the first version of this file gave bi_reader the engine's records too: taken back
revoke all on schema bi_factory from bi_reader;
revoke all on all tables in schema bi_factory from bi_reader;
alter default privileges for role aibi_dbt_dev in schema bi_factory revoke select on tables from bi_reader;

-- ── the landed extract ─────────────────────────────────────────────────────────────────────────────────────
-- SYNTHETIC. Sixteen regions, four sites each, four technologies, ninety days ending yesterday. Every value
-- is a pure function of (site, technology, day), so two installs draw the same dashboard and a test can
-- assert a number. The table is refilled whole, in one transaction, exactly as cem_to_mart.py replaces an
-- extract — a chart never reads it half-written.
create table if not exists cem_landing.site_kpi_daily (
    kpi_date            date           not null,
    site_id             text           not null,
    site_name           text           not null,
    region_name         text           not null,
    rat                 text           not null,
    active_users        bigint         not null,
    degraded_users      bigint         not null,
    avg_throughput_mbps numeric(10, 2) not null,
    avg_latency_ms      numeric(10, 2) not null,
    drop_rate_pct       numeric(6, 3)  not null,
    landed_at           timestamptz    not null default now()
);
grant select on cem_landing.site_kpi_daily to bi_builder;

begin;
truncate cem_landing.site_kpi_daily;

insert into cem_landing.site_kpi_daily
    (kpi_date, site_id, site_name, region_name, rat, active_users, degraded_users,
     avg_throughput_mbps, avg_latency_ms, drop_rate_pct)
with regions (region_name, code, population, quality) as (
    -- population: relative size of the customer base · quality: how good the network is there, 0 to 1
    values
        ('Tanger - Tétouan',                     'TNG', 0.62, 0.80),
        ('Gharb - Chrarda - Béni Hssen',         'GHB', 0.38, 0.71),
        ('Taza - Al Hoceima - Taounate',         'TAZ', 0.33, 0.64),
        ('Oriental',                             'ORI', 0.40, 0.69),
        ('Fès - Boulemane',                      'FES', 0.42, 0.76),
        ('Meknès - Tafilalet',                   'MEK', 0.44, 0.72),
        ('Rabat - Salé - Zemmour - Zaer',        'RBT', 0.70, 0.86),
        ('Grand Casablanca',                     'CAS', 1.00, 0.88),
        ('Chaouia - Ouardigha',                  'CHA', 0.34, 0.70),
        ('Doukkala - Abda',                      'DKA', 0.36, 0.68),
        ('Marrakech - Tensift - Al Haouz',       'MRK', 0.66, 0.78),
        ('Tadla - Azilal',                       'TAD', 0.27, 0.63),
        ('Souss - Massa - Draâ',                 'SMD', 0.58, 0.74),
        ('Guelmim - Es-Semara',                  'GLM', 0.12, 0.60),
        ('Laâyoune - Boujdour - Sakia El Hamra', 'LAY', 0.10, 0.62),
        ('Oued el Dahab',                        'OED', 0.05, 0.58)
),
sites as (
    select r.region_name, r.population, r.quality,
           r.code || '-' || lpad(n::text, 3, '0')      as site_id,
           'Site ' || r.code || ' ' || lpad(n::text, 3, '0') as site_name
    from regions r
    cross join generate_series(1, 4) as n
),
rats (rat, user_share, throughput_target, latency_base, drop_base) as (
    values
        ('2G', 0.04,   0.3, 230.0, 2.6),
        ('3G', 0.18,   6.0, 150.0, 1.7),
        ('4G', 0.60,  40.0,  65.0, 0.9),
        ('5G', 0.18, 150.0,  28.0, 0.5)
),
days as (
    select d::date as kpi_date
    from generate_series(current_date - 90, current_date - 1, interval '1 day') as d
),
draws as (
    select d.kpi_date, s.site_id, s.site_name, s.region_name, s.population, s.quality,
           t.rat, t.user_share, t.throughput_target, t.latency_base, t.drop_base,
           -- three repeatable draws in [0, 1)
           (abs(hashtext(s.site_id || t.rat || d.kpi_date::text || 'u')) % 10000) / 10000.0 as u1,
           (abs(hashtext(s.site_id || t.rat || d.kpi_date::text || 'q')) % 10000) / 10000.0 as u2,
           (abs(hashtext(s.site_id || t.rat || d.kpi_date::text || 'd')) % 10000) / 10000.0 as u3,
           -- a week has a shape, and the network improves slowly over the quarter
           1.0 + 0.07 * sin(2 * pi() * extract(dow from d.kpi_date) / 7.0)          as weekly,
           1.0 + 0.05 * (d.kpi_date - (current_date - 90)) / 90.0                   as drift
    from days d
    cross join sites s
    cross join rats t
),
kpis as (
    select *,
           greatest(0.35, least(0.98, quality * drift * (0.94 + 0.12 * u2)))        as q,
           round(60000 * population * user_share * weekly * (0.85 + 0.30 * u1))     as users
    from draws
)
select kpi_date, site_id, site_name, region_name, rat,
       users::bigint,
       round(users * greatest(0.01, least(0.60, 0.46 - 0.44 * q + 0.06 * u3)))::bigint,
       round((throughput_target * (0.25 + 0.75 * q) * (0.92 + 0.16 * u3))::numeric, 2),
       round((latency_base * (1.75 - q) * (0.92 + 0.16 * u1))::numeric, 2),
       round((drop_base * (1.80 - q) * (0.85 + 0.30 * u2))::numeric, 3)
from kpis;

commit;

analyze cem_landing.site_kpi_daily;

select 'cem_landing.site_kpi_daily: ' || count(*) || ' rows, ' || min(kpi_date) || ' → ' || max(kpi_date)
from cem_landing.site_kpi_daily;
