"""The transformations the engine may propose, and how a proposal becomes a dbt model.

A transformation is a PLAN first (models.ModelPlan): a governed base model, joined to a governed dimension on
its declared key, to add named columns. The SQL and the tests are rendered from the plan by the template
below. There is no path from a sentence to a .sql file that skips the plan, which is what lets the policy
engine say something exact about every generated model: one select, over ref()s of datasets the requester may
read, at the base's grain.

Every generated model carries three tests the plan implies — its grain is still unique, the added column is
never null (a region the reference does not know would otherwise be a silent hole in a map), and it has
exactly as many rows as its base.
"""
from __future__ import annotations

import hashlib
from pathlib import Path
from typing import Any, Optional

import yaml

from .dataset_agent import Gap
from .models import DatasetDef, JoinPlan, ModelPlan
from .planner import slugify
from .registry import Registry


class DbtAgent:
    def __init__(self, registry: Registry):
        self.registry = registry
        self.generated_path = registry.policies.get("dbt", {}).get("generated_models_path",
                                                                    "models/marts/ai_generated")

    # ── planning ────────────────────────────────────────────────────────────────────────────────────────────
    def plan(self, project_id: str, gaps: list[Gap],
             providers: list[tuple[DatasetDef, list[str], str]]) -> ModelPlan:
        """One model for the project's gaps: they share a base, so each provider is one more join."""
        base = gaps[0].base
        joins: list[JoinPlan] = []
        for dataset, keys, column in providers:
            existing = next((j for j in joins if j.dataset == dataset.id), None)
            if existing is None:
                joins.append(JoinPlan(dataset=dataset.id, model=dataset.source_model, on=keys, add_columns=[column]))
            elif column not in existing.add_columns:
                existing.add_columns.append(column)
        suffix = "_".join(sorted({slugify(c).replace("-", "_") for j in joins for c in j.add_columns}))
        short = base.id.split(".", 1)[-1]
        domain = base.id.split(".", 1)[0]
        added = ", ".join(c for j in joins for c in j.add_columns)
        # The project is in BOTH names. Two projects needing the same join get two drafts, each rebuilt and
        # promoted with its own project — never one table that a second project's run rewrites under a
        # dashboard the first already has in production.
        owner = slugify(project_id).replace("-", "_")
        return ModelPlan(
            name=f"aigen_{owner}__{short}_{suffix}",
            dataset_id=f"{domain}.{owner}__{short}_{suffix}",
            description=(f"{base.name} with {added} from "
                         + ", ".join(self.registry.dataset(j.dataset).name for j in joins)
                         + f". Generated for BI project {project_id}; same grain as {base.id}."),
            base_dataset=base.id,
            base_model=base.source_model,
            columns=list(base.columns),
            joins=joins,
            grain=list(base.grain),
            reason="; ".join(dict.fromkeys(g.reason for g in gaps)),
        )

    # ── rendering ───────────────────────────────────────────────────────────────────────────────────────────
    def render_sql(self, plan: ModelPlan, project_id: str, request_id: str) -> str:
        lines = [
            f"{{{{ config(materialized='table', tags=['ai_generated', 'project__{slugify(project_id)}']) }}}}",
            "",
            f"-- Generated by the SharpSight AI BI service for project {project_id} (request {request_id}).",
            f"-- {plan.reason}.",
            "-- Do not edit by hand: it is rendered from a plan, and regenerated with it.",
            "with base as (",
            "",
            f"    select * from {{{{ ref('{plan.base_model}') }}}}",
            "",
            ")",
        ]
        for index, join in enumerate(plan.joins, start=1):
            columns = ", ".join(dict.fromkeys([*join.on, *join.add_columns]))
            lines += [f", joined_{index} as (", "",
                      f"    select {columns} from {{{{ ref('{join.model}') }}}}", "", ")"]
        select = [f"    base.{column}" for column in plan.columns]
        for index, join in enumerate(plan.joins, start=1):
            select += [f"    joined_{index}.{column}" for column in join.add_columns]
        lines += ["", "select", ",\n".join(select), "from base"]
        for index, join in enumerate(plan.joins, start=1):
            condition = " and ".join(f"base.{key} = joined_{index}.{key}" for key in join.on)
            lines.append(f"left join joined_{index} on {condition}")
        return "\n".join(lines) + "\n"

    def render_yaml(self, plan: ModelPlan, project_id: str) -> str:
        columns: list[dict[str, Any]] = []
        base = self.registry.dataset(plan.base_dataset)
        for name in plan.columns:
            entry: dict[str, Any] = {"name": name, "description": base.columns[name].description}
            if name in plan.grain:
                entry["data_tests"] = ["not_null"]
            columns.append(entry)
        for join in plan.joins:
            provider = self.registry.dataset(join.dataset)
            for name in join.add_columns:
                columns.append({"name": name, "description": provider.columns[name].description,
                                "data_tests": ["not_null"]})
        document = {"version": 2, "models": [{
            "name": plan.name,
            "description": plan.description,
            "meta": {"sharpsight_dataset": plan.dataset_id, "generated_by": "sharpsight-ai-bi",
                     "project": project_id, "certified": False, "derived_from": plan.base_dataset},
            "data_tests": [
                {"unique_combination": {"arguments": {"combination_of_columns": plan.grain}}},
                {"equal_rowcount": {"arguments": {"compare_model": f"ref('{plan.base_model}')"}}},
            ],
            "columns": columns,
        }]}
        return yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=110)

    def write(self, plan: ModelPlan, workspace: Path, project_id: str, request_id: str) -> list[dict[str, str]]:
        """Write the model and its tests into the workspace. Returns each file with its hash, for the audit."""
        folder = workspace / self.generated_path / slugify(project_id).replace("-", "_")
        folder.mkdir(parents=True, exist_ok=True)
        files = {folder / f"{plan.name}.sql": self.render_sql(plan, project_id, request_id),
                 folder / f"_{plan.name}.yml": self.render_yaml(plan, project_id)}
        written = []
        for path, content in files.items():
            path.write_text(content, encoding="utf-8", newline="\n")
            written.append({"path": str(path.relative_to(workspace)).replace("\\", "/"),
                            "sha256": hashlib.sha256(content.encode()).hexdigest()})
        return written

    # ── registering what was built ──────────────────────────────────────────────────────────────────────────
    def dataset_for(self, plan: ModelPlan, project_id: str, schema: str,
                    catalog_columns: Optional[dict[str, Any]] = None) -> DatasetDef:
        """The generated model as a dataset. Its columns keep the classification of the governed column they
        come from — a generated dataset never lowers one — and it is not certified, whoever asked."""
        base = self.registry.dataset(plan.base_dataset)
        columns = {name: base.columns[name].model_copy() for name in plan.columns}
        for join in plan.joins:
            provider = self.registry.dataset(join.dataset)
            for name in join.add_columns:
                columns[name] = provider.columns[name].model_copy()
        if catalog_columns:
            absent = [name for name in columns if name not in catalog_columns]
            if absent:
                raise ValueError(f"the built model has no column {', '.join(absent)}")
        return DatasetDef(
            id=plan.dataset_id,
            name=f"{base.name} ({', '.join(c for j in plan.joins for c in j.add_columns)})",
            owner=base.owner, certified=False, kind=base.kind,
            source_type="dbt", source_model=plan.name,
            freshness_sla_minutes=base.freshness_sla_minutes, domain=base.domain, tenant=base.tenant,
            version="0.1.0-dev", description=plan.description, grain=list(plan.grain),
            time_column=base.time_column, freshness_column=base.freshness_column,
            tags=[*base.tags, "ai_generated"], columns=columns,
            generated_by="sharpsight-ai-bi", project=project_id,
            derived_from=[plan.base_dataset, *[j.dataset for j in plan.joins]],
            environment="dev", db_schema=schema,
        )
